# -*- coding: utf-8 -*-
import numpy as np
from scipy import stats
import sad_corr_core as CC
import sad_breeding_ui as U
from sad_breeding_ui import sec_table, sec_text, sec_fig
from sad_ordinal_core import p_adjust

PARTIAL_HELP = """ЧАСТИННА Й НАПІВЧАСТИННА КОРЕЛЯЦІЯ

ЧАСТИННА кореляція показує зв'язок двох ознак після виключення лінійного впливу контрольних ознак (напр., зв'язок
урожайності з масою 1000 зерен, коли «вирівняно» вплив густоти насадження). Рахується як кореляція залишків обох
ознак після регресії на контрольні. Ступені свободи: n − 2 − k, де k — кількість контрольних ознак.
НАПІВЧАСТИННА (часткова) кореляція sr — кореляція ознаки-результату із залишком пояснювальної ознаки після
виключення контрольних; її квадрат sr² — унікальний внесок пояснювальної ознаки в дисперсію результату (ΔR²).
Для двох ознак sr залежить від того, яку вважати результатом, тому наведено обидва напрями.

ЯК ЧИТАТИ ПОРІВНЯННЯ «звичайна → частинна»
• Зв'язок ЗНИКАЄ після контролю — звичайна кореляція значуща, частинна ні: ймовірно, зв'язок зумовлений спільною
  причиною (контрольною ознакою) або опосередкований нею.
• Зв'язок ПРОЯВЛЯЄТЬСЯ лише після контролю — контрольна ознака «маскувала» його (супресія).
• Знак змінився — характерно для сильної залежності між ознаками; тлумачити з великою обережністю.

ВАЖЛИВО
• Це не доказ причинності: програма не знає, які ознаки є причиною. Контроль медіатора (ознаки «на шляху» від
  причини до наслідку) або колайдера (ознаки, на яку впливають обидві) може ЗІПСУТИ висновок.
• Лінійна модель: нелінійні залежності від контрольних ознак повністю не виключаються.
• Береться ПОВНА вибірка — лише рядки, де є значення за ВСІМА задіяними ознаками; кількість відкинутих рядків
  наведено. Для кожної пари n однакове.
• Частинний Спірмен — наближення (кореляція рангів залишків за рангами змінних); p й інтервал орієнтовні.
• Кендалл для частинної кореляції не реалізовано.
• Інтервали — Фішера з SE = 1/√(n − 3 − k), БЕЗ поправки на множинність; висновок — за p з поправкою."""


def sections_partial(arrays, labels, control_idx, target_idx, method="pearson", alpha=0.05, correction="holm"):
    M = CC.partial_matrix(arrays, labels, control_idx, target_idx, method, alpha, correction)
    pairs = M["pairs"]; n = M["n"]; k = M["k"]
    # p звичайної кореляції на ТІЙ САМІЙ вибірці (t-наближення) + та сама поправка — для чесного порівняння
    p0 = []
    for q in pairs:
        r0 = q["r0"]; df0 = n - 2
        p0.append(float(2 * stats.t.sf(abs(r0) * np.sqrt(df0 / max(1 - r0 * r0, 1e-300)), df0)))
    p0a = list(p_adjust(p0, correction)) if correction != "none" and p0 else p0
    rows, tags = [], []
    sym = "ρ" if method == "spearman" else "r"
    for q, pz, pza in sorted(zip(pairs, p0, p0a), key=lambda t: -abs(t[0]["r"])):
        sp = q["p_adj"] < alpha; sz = pza < alpha
        verdict = ("зберігається" if (sp and sz) else "зникає після контролю" if (sz and not sp) else
                   "проявляється лише після контролю" if (sp and not sz) else "не істотний")
        tag = ("warn" if (sz and not sp) else "info" if (sp and not sz) else
               ("good" if (sp and q["r"] > 0) else "bad" if (sp and q["r"] < 0) else None))
        rows.append([q["a"], q["b"], q["r0"], pza, q["r"], q["ci_lo"], q["ci_hi"], q["p_raw"], q["p_adj"],
                     q["r"] - q["r0"], verdict]); tags.append(tag)
    meth = "Спірмен (наближення)" if method == "spearman" else "Пірсон"
    notes = [f"Контрольні ознаки (k = {k}): {', '.join(M['controls'])}. Метод: {meth}; поправка: {CC.CORRECTION_LABEL.get(correction, correction)}; α = {alpha}.",
             f"Спільна вибірка: n = {n} (df = {n - 2 - k}); відкинуто рядків через пропуски: {M['dropped_rows']}. Звичайна кореляція у цій таблиці "
             f"рахована на тих самих {n} рядках — щоб порівняння було коректним.",
             "Жовте — зв'язок зникає після контролю; блакитне — проявляється лише після контролю; зелене/червоне — істотний додатний/від'ємний.",
             f"p для звичайної {sym} має ту саму поправку на множинність; ДІ — без поправки."]
    S = [sec_table("Частинні кореляції", ["Ознака 1", "Ознака 2", f"{sym} звичайна", "p звичайної", f"{sym} частинна",
                                          "ДІ від", "ДІ до", "p (сире)", "p (з попр.)", "Δ", "Висновок"], rows,
                   [None, None, 3, "p", 3, 3, 3, "p", "p", 3, None], notes, tags=tags, key="partial")]
    # напівчастинні
    srows = []
    for q in sorted(pairs, key=lambda q: -max(abs(q["sr_x"]), abs(q["sr_y"]))):
        srows.append([q["a"], q["b"], q["sr_y"], 100 * q["sr_y"] ** 2, q["sr_x"], 100 * q["sr_x"] ** 2, q["p_adj"]])
    S.append(sec_table("Напівчастинні кореляції",
                       ["Ознака 1", "Ознака 2", "sr: внесок 2-го у 1-й", "sr², %", "sr: внесок 1-го у 2-й", "sr², %", "p (з поправкою)"],
                       srows, [None, None, 3, 2, 3, 2, "p"],
                       ["sr² — унікальний внесок пояснювальної ознаки в дисперсію результату після виключення контрольних (ΔR²), у відсотках.",
                        "Тест sr = 0 еквівалентний тесту коефіцієнта в регресії, тому p збігається з p частинної кореляції."], key="semi"))
    # теплова карта частинної матриці
    tl = M["targets"]; idx = {l: i for i, l in enumerate(tl)}; H = np.eye(len(tl))
    for q in pairs: H[idx[q["a"]], idx[q["b"]]] = H[idx[q["b"]], idx[q["a"]]] = q["r"]
    S.append(sec_fig("Графік: матриця частинних кореляцій", lambda f: U.fig_heat(
        f, H, tl, tl, f"Частинні кореляції (контроль: {', '.join(M['controls'])})", "частинна " + sym),
        size=(max(5.5, 1.0 * len(tl) + 3), max(4.6, 0.9 * len(tl) + 2.5)), key="heat"))
    top = sorted(pairs, key=lambda q: -abs(q["r0"]))[:15]
    S.append(sec_fig("Графік: звичайна й частинна", lambda f: U.fig_bars(
        f, [f"{q['a']}\n{q['b']}" for q in top], {f"{sym} звичайна": [q["r0"] for q in top], f"{sym} частинна": [q["r"] for q in top]},
        "Як змінюється зв'язок після виключення контрольних ознак", sym),
        size=(max(6.5, 0.7 * len(top) + 3), 4.8), key="bars"))
    S.append(sec_text("Пояснення", PARTIAL_HELP, key="help"))
    warns = []
    if M["dropped_rows"]: warns.append(f"Через пропуски відкинуто {M['dropped_rows']} рядків (залишилось n = {n}).")
    if method == "spearman": warns.append("Частинний Спірмен — наближення (кореляція рангів залишків); p та інтервал орієнтовні.")
    if n < 30: warns.append(f"Спільна вибірка невелика (n = {n}): частинні кореляції дуже непевні — дивіться довірчі інтервали.")
    if k * 5 > n: warns.append(f"Контрольних ознак ({k}) багато щодо вибірки (n = {n}): оцінки нестійкі.")
    return S, warns, M
